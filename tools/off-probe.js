#!/usr/bin/env node
// Probes Open Food Facts v2 for every valid fixture EAN, snapshots the responses and writes docs/off-findings.md.
// Usage: node tools/off-probe.js [--refresh]   (reuses test/fixtures/off-snapshot.json unless --refresh)
const fs = require("fs");
const path = require("path");
const Lib = require("../lib.js");

const ROOT = path.join(__dirname, "..");
const FIXTURE = path.join(ROOT, "test/fixtures/be-products.json");
const SNAP = path.join(ROOT, "test/fixtures/off-snapshot.json");
const OUT = path.join(ROOT, "docs/off-findings.md");
const FIELDS = "code,product_name,product_name_nl,product_name_fr,product_name_en,generic_name,brands,quantity,image_front_url,categories_tags,stores_tags,countries_tags,nutriscore_grade";
const UA = "food-scan-poc/0.1 (github.com/VLjoris/food-scan)";
const sleep = ms => new Promise(r => setTimeout(r, ms));

const rows = JSON.parse(fs.readFileSync(FIXTURE, "utf8"));
const valid = rows.filter(r => r.expectValid);
const canon = r => Lib.normalizeEan(r.ean, r.symbology);
// Extra probe: the raw 12-digit UPC-A, to compare with its 0-prefixed EAN-13 lookup.
const rawUpc = valid.filter(r => r.symbology === "UPC_A").map(r => r.ean);

let snap = fs.existsSync(SNAP) ? JSON.parse(fs.readFileSync(SNAP, "utf8")) : {};
const refresh = process.argv.includes("--refresh");

async function fetchOne(ean) {
  const url = `https://world.openfoodfacts.org/api/v2/product/${ean}.json?fields=${FIELDS}`;
  for (let attempt = 0; attempt < 6; attempt++) {
    let res;
    try { res = await fetch(url, { headers: { "User-Agent": UA } }); } catch (e) { await sleep(2000 * 2 ** attempt); continue; }
    if (res.status === 503 || res.status === 429) { await sleep(2000 * 2 ** attempt); continue; }
    let body = null;
    try { body = await res.json(); } catch {}
    if (res.status >= 500) { await sleep(2000 * 2 ** attempt); continue; }
    return { fetchedAt: new Date().toISOString(), httpStatus: res.status, body };
  }
  throw new Error("giving up on " + ean);
}

async function main() {
  const keys = [...new Set([...valid.map(canon), ...rawUpc])];
  const todo = keys.filter(k => refresh || !snap[k]);
  for (let i = 0; i < todo.length; i++) {
    const t0 = Date.now();
    snap[todo[i]] = await fetchOne(todo[i]);
    const s = snap[todo[i]];
    console.error(`[${i + 1}/${todo.length}] ${todo[i]} http=${s.httpStatus} status=${s.body && s.body.status}`);
    fs.writeFileSync(SNAP, JSON.stringify(sorted(snap), null, 1) + "\n");
    const wait = 1100 - (Date.now() - t0);
    if (wait > 0 && i < todo.length - 1) await sleep(wait);
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, report(keys, todo.length));
  console.error("wrote " + path.relative(ROOT, OUT));
}
const sorted = o => Object.fromEntries(Object.keys(o).sort().map(k => [k, o[k]]));

// ---------- analysis ----------
const pct = (n, d) => (d ? (100 * n / d).toFixed(1) + "%" : "n/a");
const cell = (n, d) => `${n}/${d} (${pct(n, d)})`;
const table = (head, body) => "| " + head.join(" | ") + " |\n|" + head.map(() => "---").join("|") + "|\n" + body.map(r => "| " + r.join(" | ") + " |").join("\n") + "\n";
const biased = r => r.source.type === "off-stores" || r.source.type === "synthetic";
const tokens = s => new Set(String(s).toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").split(/[^a-z0-9]+/).filter(Boolean));
const jac = (a, b) => { const A = tokens(a), B = tokens(b); const i = [...A].filter(x => B.has(x)).length; const u = new Set([...A, ...B]).size; return u ? i / u : 0; };

function enrich(r) {
  const key = canon(r);
  const s = snap[key];
  const m = s ? Lib.mapOffProduct(s.body) : null;
  return { ...r, key, snap: s, m, hit: !!m };
}

function report(keys, fetched) {
  const E = valid.map(enrich);
  const unbiased = E.filter(r => !biased(r));
  const stores = [...new Set(E.map(r => r.store))].sort();
  const maxFetched = Object.values(snap).map(s => s.fetchedAt).sort().pop();
  const o = [];
  const w = s => o.push(s);

  w("# Open Food Facts lookup findings\n");
  w("Generated by `node tools/off-probe.js` from `test/fixtures/off-snapshot.json` (latest snapshot fetch: " + maxFetched + "). Do not edit by hand.\n");

  w("## 1. Method\n");
  const uniq = new Set(E.map(r => r.key));
  w(`- Fixture: ${rows.length} rows, ${valid.length} with \`expectValid\`, ${uniq.size} distinct canonical EANs queried (invalid-checksum rows are never looked up, as in the app).`);
  w("- Endpoint: `GET /api/v2/product/{ean}.json?fields=" + FIELDS + "` on world.openfoodfacts.org, User-Agent `" + UA + "`, ≤1 req/s, retry with backoff on 503/429.");
  w("- Lookup key = `Lib.normalizeEan` canonical form (UPC-A → 0-prefixed EAN-13, GTIN-14 with leading 0 → EAN-13, UPC-E expanded). HTTP 404 / `status:0` = not found (a normal answer).");
  w("- A **hit** = `Lib.mapOffProduct` returns a product (status 1). Completeness is measured on hits; \"name\" = `Lib.pickName` non-empty.");
  w("- Rows with source type `off-stores` (found via OFF stores facets) or `synthetic` are biased toward OFF-known products and excluded from the headline stats; shown \"with\" them only for contrast.");
  const byType = {};
  E.forEach(r => (byType[r.source.type] = (byType[r.source.type] || 0) + 1));
  w("- Valid rows by source: " + Object.entries(byType).map(([k, v]) => `${k}=${v}`).join(", ") + ".\n");
  const httpCounts = {};
  keys.forEach(k => { const s = snap[k]; const c = s ? s.httpStatus : "missing"; httpCounts[c] = (httpCounts[c] || 0) + 1; });
  w("HTTP statuses over distinct keys: " + Object.entries(httpCounts).map(([k, v]) => `${k}×${v}`).join(", ") + ".\n");

  // hit rate
  w("## 2. Hit rate\n");
  const hr = (set, f) => { const x = set.filter(f); return cell(x.filter(r => r.hit).length, x.length); };
  const kinds = [["a-brand", r => !r.privateLabel], ["private-label", r => r.privateLabel]];
  const mk = set => [...stores.map(s => [s, ...kinds.map(([, f]) => hr(set, r => r.store === s && f(r))), hr(set, r => r.store === s)]),
    ["**all**", ...kinds.map(([, f]) => hr(set, f)), hr(set, () => true)]];
  const head = ["store", "a-brand", "private label", "total"];
  w("Excluding `off-stores`/`synthetic` (unbiased; rows = fixture rows, so a product at 2 stores counts twice):\n");
  w(table(head, mk(unbiased)));
  w("Including them (biased, for contrast):\n");
  w(table(head, mk(E)));
  const ub = new Set(unbiased.map(r => r.key));
  const ubHit = new Set(unbiased.filter(r => r.hit).map(r => r.key));
  w(`Distinct unbiased EANs: ${ub.size}, found: ${cell(ubHit.size, ub.size)}.\n`);
  w("By source type:\n");
  w(table(["source", "hits"], Object.keys(byType).sort().map(t => [t, hr(E, r => r.source.type === t)])));
  const bySym = [...new Set(E.map(r => r.symbology))].sort();
  w("By symbology (all valid rows):\n");
  w(table(["symbology", "hits"], bySym.map(t => [t, hr(E, r => r.symbology === t)])));
  const miss = unbiased.filter(r => !r.hit);
  w("Unbiased misses:\n");
  w(miss.length ? table(["EAN", "store", "kind", "label"], miss.map(r => [r.key, r.store, r.kind, r.label])) : "_none_\n");

  // completeness
  w("## 3. Field completeness (hits only)\n");
  const fields = [["name", r => r.m.completeness.name], ["NL name", r => r.m.completeness.nameNl], ["FR name", r => r.m.completeness.nameFr],
    ["brand", r => r.m.completeness.brand], ["quantity", r => r.m.completeness.quantity], ["image", r => r.m.hasImage]];
  const comp = set => { const h = set.filter(r => r.hit); return fields.map(([, f]) => cell(h.filter(f).length, h.length)); };
  w("Unbiased hits, overall and per store:\n");
  w(table(["scope", "hits", ...fields.map(f => f[0])],
    [["**all**", unbiased.filter(r => r.hit).length, ...comp(unbiased)], ...stores.map(s => { const x = unbiased.filter(r => r.store === s); return [s, x.filter(r => r.hit).length, ...comp(x)]; })]));
  w("Unbiased hits, a-brand vs private label:\n");
  w(table(["scope", "hits", ...fields.map(f => f[0])], kinds.map(([n, f]) => { const x = unbiased.filter(f); return [n, x.filter(r => r.hit).length, ...comp(x)]; })));
  w("All valid hits incl. biased rows (contrast):\n");
  w(table(["scope", "hits", ...fields.map(f => f[0])], [["all", E.filter(r => r.hit).length, ...comp(E)]]));

  // cross-store
  w("## 4. Cross-store groups\n");
  const groups = {};
  E.forEach(r => (groups[r.group] = groups[r.group] || []).push(r));
  const cross = Object.entries(groups).filter(([, v]) => new Set(v.map(r => r.store)).size >= 2).sort();
  w(`${cross.length} of ${Object.keys(groups).length} groups appear at ≥2 stores.\n`);
  w(table(["group", "stores", "distinct EANs", "OFF names (distinct)", "same EAN ⇒ same name"],
    cross.map(([g, v]) => {
      const eans = [...new Set(v.map(r => r.key))];
      const names = [...new Set(eans.map(k => { const r = v.find(x => x.key === k); return r.hit ? r.m.name : "(not found)"; }))];
      return [g, [...new Set(v.map(r => r.store))].sort().join(", "), eans.length, names.join(" ⁄ "), "yes"];
    })));
  w("Same EAN ⇒ identical name holds by construction (one OFF record per EAN, the lookup is store-independent); store is not part of the OFF key.\n");
  const flagged = [];
  Object.entries(groups).sort().forEach(([g, v]) => {
    const byLabel = {};
    v.forEach(r => (byLabel[r.label] = byLabel[r.label] || new Set()).add(r.key));
    Object.entries(byLabel).forEach(([label, set]) => {
      if (set.size > 1) flagged.push([g, label, [...set].join(", "), v.filter(r => set.has(r.key)).map(r => `${r.store}:${r.key}`).join("; ")]);
    });
  });
  w("Groups where the fixture says the same product (identical label) but EANs differ:\n");
  w(flagged.length ? table(["group", "label", "EANs", "store:EAN"], flagged) : "_none_\n");

  // variants
  w("## 5. Variant groups (different EAN, same product family)\n");
  const varRows = [];
  Object.entries(groups).sort().forEach(([g, v]) => {
    const eans = [...new Set(v.map(r => r.key))];
    for (let i = 0; i < eans.length; i++) for (let j = i + 1; j < eans.length; j++) {
      const a = v.find(r => r.key === eans[i]), b = v.find(r => r.key === eans[j]);
      if (a.hit && b.hit) varRows.push([g, `${a.key} ${a.m.name}${a.m.quantity ? " [" + a.m.quantity + "]" : ""}`, `${b.key} ${b.m.name}${b.m.quantity ? " [" + b.m.quantity + "]" : ""}`, jac(a.m.name, b.m.name).toFixed(2), a.m.name === b.m.name ? "yes" : "no"]);
    }
  });
  w(`${varRows.length} EAN pairs inside the same group, both found in OFF. Similarity = Jaccard over lowercase accent-stripped name tokens.\n`);
  w(table(["group", "EAN A", "EAN B", "name sim", "identical name"], varRows));
  if (varRows.length) {
    const sims = varRows.map(r => +r[3]);
    w(`Mean similarity ${(sims.reduce((a, b) => a + b, 0) / sims.length).toFixed(2)}; identical names: ${varRows.filter(r => r[4] === "yes").length}/${varRows.length}; pairs with sim < 0.5: ${sims.filter(s => s < 0.5).length}.\n`);
  }
  const grpNotFound = Object.entries(groups).filter(([, v]) => v.some(r => !r.hit) && v.some(r => r.hit)).map(([g]) => g).sort();
  w("Groups with both found and not-found EANs (a group cannot be derived from OFF alone): " + (grpNotFound.join(", ") || "none") + ".\n");

  // name quality
  w("## 6. Name-quality issues (hits, all valid rows deduplicated by EAN)\n");
  const seen = new Set();
  const hits = E.filter(r => r.hit && !seen.has(r.key) && seen.add(r.key));
  const issues = {
    "store/country suffix in name (e.g. `6petfl BEL`)": r => /\b(BEL|BE|NL|FR|BELG\w*)\s*$/.test(r.m.name) || /\d\s*(petfl|fl|pet|blik|dos)\b/i.test(r.m.name),
    "implausible quantity (≤1 g/ml, e.g. `1 gram`)": r => { const q = /^\s*(\d+(?:[.,]\d+)?)\s*(g|gr|gram|ml|cl)\b/i.exec(r.m.quantity); return !!q && parseFloat(q[1].replace(",", ".")) <= 1; },
    "quantity missing": r => !r.m.quantity,
    "brand missing": r => !r.m.brand,
    "no NL name": r => !r.m.names.nl,
    "no FR name": r => !r.m.names.fr,
    "neither NL nor FR name": r => !r.m.names.nl && !r.m.names.fr,
    "ALL-CAPS name": r => /[A-Z]{3}/.test(r.m.name) && r.m.name === r.m.name.toUpperCase(),
    "name differs from the NL name (language mix)": r => !!r.m.names.nl && r.m.names.nl !== r.m.name,
    "name contains digits+unit (quantity embedded in name)": r => /\b\d+([.,]\d+)?\s?(g|kg|ml|cl|l)\b/i.test(r.m.name),
    "empty/missing name": r => !r.m.name,
  };
  const ex = {};
  w(table(["issue", "count", "share of hits"], Object.entries(issues).map(([k, f]) => { const x = hits.filter(f); ex[k] = x; return [k, x.length, pct(x.length, hits.length)]; })));
  w(`Denominator: ${hits.length} distinct found EANs.\n`);
  Object.entries(ex).forEach(([k, x]) => {
    if (!x.length || /missing$|^no |neither/.test(k)) return;
    w(`**${k}** — examples:\n`);
    x.slice(0, 8).forEach(r => w(`- ${r.key} (${r.store}): name=\`${r.m.name}\`, quantity=\`${r.m.quantity}\`, brand=\`${r.m.brand}\`, nl=\`${r.m.names.nl}\`, fr=\`${r.m.names.fr}\``));
    w("");
  });
  const fb = { nl: 0, fr: 0, en: 0, generic: 0, none: 0 };
  hits.forEach(r => { const b = r.snap.body.product; if (r.m.names.nl) fb.nl++; else if (r.m.names.fr) fb.fr++; else if (r.m.names.en) fb.en++; else if ((b.generic_name || "").trim()) fb.generic++; else fb.none++; });
  w("Best name available via the chain nl → fr → en → generic (ignoring `product_name`): " + Object.entries(fb).map(([k, v]) => `${k}=${v}`).join(", ") + ".\n");
  const pn = hits.filter(r => (r.snap.body.product.product_name || "").trim()).length;
  w(`\`product_name\` (canonical) present: ${cell(pn, hits.length)}.\n`);

  // edge
  w("## 7. Variable-weight and edge-case behavior\n");
  const edge = E.filter(r => r.kind === "edge-case" || r.symbology !== "EAN_13");
  w(table(["EAN (fixture)", "symbology", "lookup key", "variable-weight", "BE prefix", "OFF found", "name", "source"],
    edge.map(r => [r.ean, r.symbology, r.key, Lib.isVariableWeight(r.key) ? "yes" : "no", Lib.isBelgianPrefix(r.key) ? "yes" : "no", r.hit ? "yes" : "no", r.hit ? r.m.name : "", r.source.type])));
  const vw = E.filter(r => Lib.isVariableWeight(r.key));
  w(`Variable-weight (2x prefix) rows: ${vw.length}; found in OFF: ${vw.filter(r => r.hit).length}. These codes embed a price/weight, are store-internal, and are not in OFF — the app should detect them with \`Lib.isVariableWeight\` and not offer an OFF lookup.\n`);
  w("UPC-A handling:\n");
  rawUpc.forEach(u => {
    const c = Lib.normalizeEan(u, "UPC_A"), a = snap[c], b = snap[u];
    const f = s => (s ? `HTTP ${s.httpStatus}, status ${s.body && s.body.status}` : "not probed");
    w(`- UPC-A \`${u}\` → EAN-13 \`${c}\`: ${f(a)}; raw 12-digit query: ${f(b)}${a && b && a.body && b.body && a.body.status === b.body.status ? " (same answer)" : ""}.`);
  });
  w("");
  const invalid = rows.filter(r => !r.expectValid);
  w(`${invalid.length} invalid-checksum rows are rejected by \`Lib.normalizeEan\` before any network call (0 requests).\n`);

  // recommendation
  w("## 8. Recommendation for the app data model\n");
  const h = unbiased.filter(r => r.hit);
  w(`Based on the numbers above (unbiased hit rate ${cell(h.length, unbiased.length)}; NL name ${pct(h.filter(r => r.m.completeness.nameNl).length, h.length)}, FR ${pct(h.filter(r => r.m.completeness.nameFr).length, h.length)}, brand ${pct(h.filter(r => r.m.completeness.brand).length, h.length)}, quantity ${pct(h.filter(r => r.m.completeness.quantity).length, h.length)}, image ${pct(h.filter(r => r.m.hasImage).length, h.length)} of hits):\n`);
  w("1. **Keep the canonical EAN-13/EAN-8 as the only primary key.** Same EAN ⇒ same OFF record at every store, so store is an attribute of a sighting/price, never of the product key.");
  w("2. **Add an optional local `group`/canonical-name field** (e.g. `nutella`) only as a user-level link between EANs: different sizes/pack types are different EANs with similar but not identical names (section 5), and retailer-equal products can carry different EANs (section 4). Do not try to infer it from OFF.");
  w("3. **Store user-override names** (`userName`) separate from the cached OFF data, because OFF names carry suffixes, caps or wrong quantities (section 6) and misses need a manual name anyway. Display precedence: userName → OFF name chain.");
  w("4. **Name fallback chain nl → fr → en → generic** (as `Lib.pickName`, after canonical `product_name`), with the caller's UI language first; no single language field is complete (section 3).");
  w("5. **Display `brand + quantity` next to the name** (separately from the name) and treat quantity as untrusted when ≤1 g or missing; prefer the fixture/user value then.");
  w("6. **Do not look up variable-weight (2x) codes**; for OFF misses (esp. private label) fall back to manual naming and optionally offer an OFF contribution link. Cache snapshots locally and tolerate 503/429 with retry.\n");
  return o.join("\n") + "\n";
}

main().catch(e => { console.error(e); process.exit(1); });
